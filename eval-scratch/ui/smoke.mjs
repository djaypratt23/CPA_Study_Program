import { launch, BASE, DESKTOP, collectErrors, onboard } from './lib.mjs'
const b = await launch()
const ctx = await b.newContext({ viewport: DESKTOP })
const page = await ctx.newPage()
const errs = []; collectErrors(page, errs)
const t0 = Date.now()
await page.goto(BASE)
await page.waitForSelector('h1')
console.log('first h1 after', Date.now() - t0, 'ms; url', page.url())
await page.screenshot({ path: 'shots/smoke-welcome.png' })
await onboard(page)
await page.screenshot({ path: 'shots/smoke-dash.png', fullPage: true })
console.log(await page.locator('main').innerText().then(t => t.slice(0, 1500)))
console.log('ERRS', errs)
await b.close()
